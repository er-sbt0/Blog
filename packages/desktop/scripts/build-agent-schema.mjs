/**
 * Bundle the content bridge's op schema and its prose into the main process
 * (docs/plans/agent-block.md §7, phase-0 note 2).
 *
 * The doc tools are declared in `src/agent.js`, and the model is told what a
 * block may be by whatever schema and description that declaration carries. In
 * phase 0 that was a loose `{ type: string }` shape, because the real one —
 * `opSchema`, `BLOCK_DOC` and `RECOVERY_DOC` in `src/lib/content-bridge/
 * schema.ts` — is TypeScript under the repository's `@/` tree, which this
 * plain-JS package cannot import (the general rule `build-mcp.mjs` states:
 * anything that imports from `src/` runs only where the repository is). So
 * the model was told less than blog-content tells it, about the same tools.
 *
 * This compiles that one file with esbuild, the way `build-mcp.mjs` compiles
 * the MCP server, into `src/generated/docSchema.mjs` — inside `src/`, so
 * electron-builder's `files: src/**` packages it with no new rule.
 *
 * **`zod` is external, deliberately.** The schema is written against the root's
 * zod 3; the SDK peers on zod 4, and this package depends on zod 4 for that
 * reason. Left external, the bundle's `import "zod"` resolves from
 * `src/generated/` to *this package's* zod — the same instance the SDK's
 * `tool()` converts to JSON Schema — and the file only uses API the two majors
 * share (`object`, `discriminatedUnion`, `literal`, `enum`, `array`, `unknown`,
 * `default`, `describe`). Bundling zod 3 in instead would hand the SDK a schema
 * from a second zod it would then have to recognise.
 *
 * Fast (tens of milliseconds), so `pnpm desktop` and `pnpm desktop:dev` run it
 * on every launch rather than trusting a stale copy; `stage-resources.mjs`
 * runs it before packaging, and `pnpm build:desktop` after the Next build.
 */
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const packageRoot = path.resolve(here, "..");
const repoRoot = path.resolve(packageRoot, "..", "..");
const require = createRequire(path.join(packageRoot, "package.json"));

export const AGENT_SCHEMA_ENTRY = path.join(repoRoot, "src", "lib", "content-bridge", "schema.ts");
export const AGENT_SCHEMA_BUNDLE = path.join(packageRoot, "src", "generated", "docSchema.mjs");

export async function buildAgentSchema({ outfile = AGENT_SCHEMA_BUNDLE, log = () => {} } = {}) {
  const esbuild = require("esbuild");
  fs.mkdirSync(path.dirname(outfile), { recursive: true });
  await esbuild.build({
    entryPoints: [AGENT_SCHEMA_ENTRY],
    outfile,
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node22",
    external: ["zod"],
    banner: {
      js:
        "// Generated by packages/desktop/scripts/build-agent-schema.mjs from\n" +
        "// src/lib/content-bridge/schema.ts. Do not edit; it is rebuilt on launch.",
    },
    logLevel: "silent",
  });
  log(`agent doc schema bundled -> ${path.relative(repoRoot, outfile)}`);
  return outfile;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  await buildAgentSchema({ log: (line) => console.warn(`[agent-schema] ${line}`) });
}
